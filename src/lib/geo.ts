export function parseCityList(value: string | null | undefined): string[] {
  if (!value?.trim()) return [];
  try {
    const parsed = JSON.parse(value) as unknown;
    if (Array.isArray(parsed)) {
      return parsed.map(String).map((s) => s.trim()).filter(Boolean);
    }
  } catch {
    /* comma-separated */
  }
  return value
    .split(/[,;|]/)
    .map((s) => s.trim())
    .filter(Boolean);
}

export function formatCityList(cities: string[]): string | null {
  const unique = [...new Set(cities.map((c) => c.trim()).filter(Boolean))];
  return unique.length ? unique.join(", ") : null;
}

export function citiesFromForm(formData: FormData, name: string): string | null {
  return formatCityList(formData.getAll(name).map(String));
}

export function withCurrentOption(list: readonly string[], current?: string | null): string[] {
  const v = current?.trim();
  if (!v) return [...list];
  if (list.includes(v)) return [...list];
  return [v, ...list];
}

export function withCurrentOptions(list: readonly string[], currents: string[]): string[] {
  const extras = currents.map((c) => c.trim()).filter((c) => c && !list.includes(c));
  return extras.length ? [...new Set(extras), ...list] : [...list];
}
